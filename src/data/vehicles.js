export function getVariantDetails(modelId, variantId) {
  const detail = Object.hasOwn(vehicleDetails, modelId)
    ? vehicleDetails[modelId]
    : undefined;
  if (!detail) return null;
  const variant =
    detail.variants.find((item) => item.id === variantId) ?? detail.variants[0];
  return {
    detail,
    variant,
    specs: { ...detail.specs, ...variant.specs },
    safety: [...new Set([...detail.safety, ...variant.safety])],
  };
}
